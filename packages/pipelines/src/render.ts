import { isDeepStrictEqual } from "node:util";
import { APP_NAME } from "@orch/core";
import { parseAllDocuments, stringify } from "yaml";
import { z } from "zod";
import type { Template } from "./loader";
import { type Manifest, paramsSchema } from "./manifest";
import { foreignKeys, isMap, PLACEHOLDER, parsePipeline, type Tree } from "./pipeline";

/** Why a pipeline could not be rendered, one line each. They name parameters, never what was given. */
export class RenderError extends Error {
  constructor(readonly problems: string[]) {
    super(`cannot render:\n${problems.join("\n")}`);
  }
}

/**
 * One layer of configuration (lowest first: the organization's defaults, the project's, an
 * environment's). `params` fill the template's placeholders, a later layer's value winning;
 * `overrides` is a piece of pipeline merged over the template's: maps merge key by key, anything
 * else (a list too) is replaced. Placeholders are the template's alone: an override is literal.
 */
const layerSchema = z.strictObject({
  params: z.record(z.string(), z.unknown()).optional(),
  overrides: z.record(z.string(), z.json()).optional(),
});
export type Layer = z.input<typeof layerSchema>;

type Scalar = string | number | boolean;
const WHOLE = new RegExp(`^${PLACEHOLDER.source}$`);

/** Fills placeholders in string values only (keys and structure are never touched). */
function fill(node: unknown, params: Record<string, Scalar | undefined>, missing: Set<string>) {
  const value = (name: string) => {
    const v = params[name];
    if (v === undefined) missing.add(name);
    return v;
  };
  const walk = (n: unknown): unknown => {
    if (typeof n === "string") {
      const whole = WHOLE.exec(n);
      // a placeholder that is the whole value keeps its type (`retry: 2`); inside text it is text
      if (whole) return value(whole[1] ?? "");
      return n.replace(PLACEHOLDER, (_, name: string) => String(value(name)));
    }
    if (Array.isArray(n)) return n.map(walk);
    if (isMap(n)) return Object.fromEntries(Object.entries(n).map(([k, v]) => [k, walk(v)]));
    return n;
  };
  return walk(node);
}

/** Maps merge, anything else on the right replaces what is on the left. Keys keep the left's order, new ones follow. */
function merge(left: unknown, right: unknown): unknown {
  if (!isMap(left) || !isMap(right)) return right;
  const keys = [...Object.keys(left), ...Object.keys(right).filter((k) => !Object.hasOwn(left, k))];
  return Object.fromEntries(
    keys.map((k) => [
      k,
      !Object.hasOwn(right, k)
        ? left[k]
        : Object.hasOwn(left, k)
          ? merge(left[k], right[k])
          : right[k],
    ]),
  );
}

/** How every rendered file begins: what tells one of ours from a hand-written file. */
export const GENERATED = `# Generated by ${APP_NAME} from template`;

/** Written as YAML 1.1 so that what GitLab's parser would read as a boolean, number or date is quoted. */
const WRITE = { version: "1.1", lineWidth: 0, indent: 2, aliasDuplicateObjects: false } as const;

/** GitLab's own template for the secret detection job (SCAN-5): included from GitLab, so nothing of it is copied into a repository. */
export const SECRET_DETECTION_TEMPLATE = "Jobs/Secret-Detection.gitlab-ci.yml";

/** The template's pipeline (or the `workflow` file's text, when that is given) as a tree; what is wrong with it is a `RenderError`. */
function treeOf(template: Template, text = template.pipeline, file = "pipeline.yml"): Tree {
  try {
    return parsePipeline(text);
  } catch (e) {
    throw new RenderError([`${file}: ${e instanceof Error ? e.message : "cannot be read"}`]);
  }
}

/**
 * Adds GitLab's secret detection to a pipeline (SCAN-5): its template after any include the pipeline has,
 * and the job it defines with two changes. GitLab's job runs in a stage called `test`, which a pipeline
 * that names its own stages may not have, so it goes in the first of `stages` then. And it takes nothing
 * from `default`: that holds the starter's image, services and install step, and none of it is for the
 * analyzer's own image.
 */
function withSecretDetection(doc: Tree, stages: unknown): Tree {
  const own =
    doc.include === undefined ? [] : Array.isArray(doc.include) ? doc.include : [doc.include];
  const stage = Array.isArray(stages) && !stages.includes("test") ? stages[0] : undefined;
  return {
    include: [...own, { template: SECRET_DETECTION_TEMPLATE }],
    ...Object.fromEntries(Object.entries(doc).filter(([k]) => k !== "include")),
    secret_detection: { ...(stage === undefined ? {} : { stage }), inherit: { default: false } },
  };
}

/** The parameters the layers give (later layers win), checked against the manifest with defaults filled, and the layers that were sound. */
function resolve(template: Template, layers: Layer[]) {
  const problems: string[] = [];
  let params: Record<string, unknown> = {};
  const clean: z.output<typeof layerSchema>[] = [];
  layers.forEach((layer, i) => {
    const parsed = layerSchema.safeParse(layer);
    if (!parsed.success) {
      for (const p of parsed.error.issues)
        problems.push(`layer ${i}: ${p.path.join(".") || "(root)"}: ${p.message}`);
      return;
    }
    // spread, not assign: a key called `__proto__` stays a key (and is refused as unknown), and a layer that says nothing (`undefined`) changes nothing
    params = {
      ...params,
      ...Object.fromEntries(
        Object.entries(parsed.data.params ?? {}).filter(([, v]) => v !== undefined),
      ),
    };
    clean.push(parsed.data);
  });
  // the platform's own switches are not the template's: they are answered here and never reach its params or inputs
  const { secretDetection, ...own } = params;
  if (secretDetection !== undefined && typeof secretDetection !== "boolean")
    problems.push("param secretDetection: must be true or false");
  const checked = paramsSchema(template.manifest).safeParse(own);
  if (!checked.success) {
    for (const p of checked.error.issues)
      problems.push(
        p.path.length > 0 ? `param ${p.path.join(".")}: ${p.message}` : `params: ${p.message}`,
      );
  }
  if (problems.length > 0 || !checked.success) throw new RenderError(problems);
  return { params: checked.data, clean, secretDetection: secretDetection === true };
}

/** Throws a `RenderError` for a layer the template refuses (an unknown or invalid parameter, a bad override); renders nothing. Cheap, so a caller can refuse before it reaches anywhere. */
export function checkLayers(template: Template, layers: Layer[] = []): void {
  resolve(template, layers);
}

/** Every document of `text`, read as YAML 1.1 and 1.2, must be the one that was written; otherwise a reader would see another pipeline. */
function readBack(text: string, ...written: unknown[]) {
  for (const version of ["1.1", "1.2"] as const) {
    const read = parseAllDocuments(text, { version, merge: true });
    if (
      read.some((d) => d.errors.length > 0) ||
      !isDeepStrictEqual(
        read.map((d) => d.toJS()),
        written,
      )
    )
      throw new RenderError(["a value cannot be written so that every YAML reader sees the same"]);
  }
}

/**
 * Renders a template to the text of a `.gitlab-ci.yml` (PIPE-3). Parameters are checked against the
 * manifest (defaults filled, unknown names refused), substituted into the template's parsed string
 * values (so a value can never become structure), the layers' overrides merged on top, and the result
 * written the same way every time. Before returning, the text is read back as YAML 1.1 and 1.2: if it
 * does not give the same document, it is refused rather than committed.
 */
export function render(template: Template, layers: Layer[] = []): string {
  const { params, clean, secretDetection } = resolve(template, layers);
  const missing = new Set<string>();
  let result = fill(treeOf(template), params as Record<string, Scalar | undefined>, missing);
  if (missing.size > 0)
    throw new RenderError([...missing].map((n) => `param ${n}: has no value and no default`));
  if (secretDetection && isMap(result)) result = withSecretDetection(result, result.stages);
  for (const layer of clean) if (layer.overrides) result = merge(result, layer.overrides);

  const { name, version } = template.manifest;
  const text = `${GENERATED} ${name}@${version}. Change the pipeline there: edits here are overwritten.\n${stringify(result, WRITE)}`;
  readBack(text, result);
  return text;
}

/**
 * Renders a template as the text of a GitHub Actions workflow (FRG-16): the template's `workflow.yml`, filled and
 * overridden exactly as `render` does its pipeline, and written the same way. Only GitHub's own keys may be in it,
 * the template's and the overrides' alike: an `include:` or a `stages:` would be a file GitHub refuses, and is
 * refused here instead. A template with no `workflow.yml` has no form for GitHub and is refused by name. Secret
 * detection is GitLab's analyzer and is refused too: dropping it silently would say a scan runs that does not.
 */
export function renderWorkflow(template: Template, layers: Layer[] = []): string {
  const { name, version } = template.manifest;
  if (template.workflow === undefined)
    throw new RenderError([`${name}@${version} has no GitHub Actions form yet`]);
  const { params, clean, secretDetection } = resolve(template, layers);
  if (secretDetection)
    throw new RenderError([
      "param secretDetection: is GitLab's analyzer, which a workflow does not run",
    ]);
  const missing = new Set<string>();
  let result = fill(
    treeOf(template, template.workflow, "workflow.yml"),
    params as Record<string, Scalar | undefined>,
    missing,
  );
  if (missing.size > 0)
    throw new RenderError([...missing].map((n) => `param ${n}: has no value and no default`));
  for (const layer of clean) if (layer.overrides) result = merge(result, layer.overrides);
  const foreign = isMap(result) ? foreignKeys(result) : undefined;
  if (foreign) throw new RenderError([foreign]);

  const text = `${GENERATED} ${name}@${version}. Change the pipeline there: edits here are overwritten.\n${stringify(result, WRITE)}`;
  readBack(text, result);
  return text;
}

/** Where a template's pipeline lives in the templates project (PIPE-9): the catalog's own layout. */
export const includePath = (m: Pick<Manifest, "name" | "version">) =>
  `${m.name}/${m.version}/pipeline.yml`;

/** The project (a path such as `group/ci-templates`) and ref an include-mode pipeline reads the template from. */
export interface IncludeTarget {
  project: string;
  /** A branch or tag; GitLab's default branch when left out. */
  ref?: string;
}
const PROJECT_PATH = /^[A-Za-z0-9_.-]+(\/[A-Za-z0-9_.-]+)+$/;
const REF = /^(?!-)(?!.*\.\.)[A-Za-z0-9_./-]{1,100}$/;

/** A GitLab project path such as `group/ci-templates`: no `.` or `..` segment, nothing that would end a YAML scalar or a URL. */
export const isProjectPath = (project: string) =>
  PROJECT_PATH.test(project) &&
  project.length <= 255 &&
  !project.split("/").some((part) => part === "." || part === "..");

/** What is wrong with the templates project and the overrides of a thin file (include and component mode alike). */
function thinProblems(
  project: string,
  clean: z.output<typeof layerSchema>[],
  mode: "include" | "component",
) {
  const problems: string[] = [];
  if (!isProjectPath(project))
    problems.push("include project: must be a project path such as group/ci-templates");
  for (const layer of clean)
    if (layer.overrides && Object.hasOwn(layer.overrides, "include"))
      problems.push(`overrides: include is the template's own in ${mode} mode`);
  return problems;
}

/** The parameters a template declares and has a value for: the `inputs` of a thin file. */
const inputsOf = (template: Template, params: Record<string, unknown>) =>
  Object.fromEntries(
    Object.keys(template.manifest.params.properties).flatMap((k) =>
      params[k] === undefined ? [] : [[k, params[k]] as const],
    ),
  );

/**
 * Renders a template as a thin `.gitlab-ci.yml` (PIPE-9): an `include:` of the template's file in the
 * templates project (see `includeFile`) with the parameters as `inputs`. The layers are resolved
 * exactly as `render` does, so both modes take the same parameters and overrides; the overrides are
 * merged over the thin file, which GitLab in turn merges over the included jobs. The file begins with
 * the same header, so the platform can tell its own.
 */
export function renderInclude(template: Template, layers: Layer[], target: IncludeTarget): string {
  const { params, clean, secretDetection } = resolve(template, layers);
  const problems = thinProblems(target.project, clean, "include");
  if (target.ref !== undefined && !REF.test(target.ref))
    problems.push("include ref: must be a branch or tag name");
  if (problems.length > 0) throw new RenderError(problems);

  const { name, version } = template.manifest;
  const inputs = inputsOf(template, params);
  const base: Tree = {
    include: [
      {
        project: target.project,
        ...(target.ref === undefined ? {} : { ref: target.ref }),
        file: includePath(template.manifest),
        ...(Object.keys(inputs).length === 0 ? {} : { inputs }),
      },
    ],
  };
  let result: unknown = secretDetection ? withSecretDetection(base, treeOf(template).stages) : base;
  for (const layer of clean) if (layer.overrides) result = merge(result, layer.overrides);
  const text = `${GENERATED} ${name}@${version}, included from ${target.project}. Change the pipeline there: edits here are overwritten.\n${stringify(result, WRITE)}`;
  readBack(text, result);
  return text;
}

/** The catalog project (a path such as `group/ci-templates`) and the version of its component that a component-mode pipeline uses. */
export interface ComponentTarget {
  project: string;
  version: string;
}
/** A release (`1.2.3`, or `1.2` and `1`, which follow the newest matching release) or a full commit SHA. */
const COMPONENT_VERSION = /^(\d+(\.\d+){0,2}|[0-9a-f]{40})$/;

/**
 * Renders a template as a thin `.gitlab-ci.yml` that uses it as a CI/CD component (CMP-2): an
 * `include:` of `$CI_SERVER_FQDN/<project>/<template name>@<version>` with the parameters as `inputs`.
 * The component file is `componentFile`, published by a person. Only a release or a full SHA is
 * accepted as the version: a branch or `~latest` moves without a merge request here, so a merged
 * pipeline could change under its owners. Otherwise as `renderInclude`.
 */
export function renderComponent(
  template: Template,
  layers: Layer[],
  target: ComponentTarget,
): string {
  const { params, clean, secretDetection } = resolve(template, layers);
  const problems = thinProblems(target.project, clean, "component");
  if (!COMPONENT_VERSION.test(target.version))
    problems.push(
      "component version: must be a release such as 1.2.3 (or 1, 1.2) or a full commit SHA, not a branch or ~latest",
    );
  if (problems.length > 0) throw new RenderError(problems);

  const { name, version } = template.manifest;
  const inputs = inputsOf(template, params);
  const base: Tree = {
    include: [
      {
        component: `$CI_SERVER_FQDN/${target.project}/${name}@${target.version}`,
        ...(Object.keys(inputs).length === 0 ? {} : { inputs }),
      },
    ],
  };
  let result: unknown = secretDetection ? withSecretDetection(base, treeOf(template).stages) : base;
  for (const layer of clean) if (layer.overrides) result = merge(result, layer.overrides);
  const text = `${GENERATED} ${name}@${version}, component of ${target.project}@${target.version}. Change the pipeline there: edits here are overwritten.\n${stringify(result, WRITE)}`;
  readBack(text, result);
  return text;
}

/** GitLab's input type of a manifest parameter type. */
const INPUT_TYPE = { string: "string", number: "number", integer: "number", boolean: "boolean" };

/**
 * The file a templates project holds for one template version (PIPE-9): a `spec:` of inputs made from
 * the manifest, then the template's pipeline with each `{{ params.x }}` as GitLab's `$[[ inputs.x ]]`.
 * A parameter with no default is a required input. Patterns, ranges and lengths are left out: GitLab's
 * `regex` is RE2 (the manifests' patterns use lookahead) and it has no range, so the platform checks
 * them when it renders the thin file.
 */
export function includeFile(template: Template): string {
  const { manifest } = template;
  const inputs = Object.fromEntries(
    Object.entries(manifest.params.properties).map(([name, p]) => [
      name,
      {
        type: INPUT_TYPE[p.type],
        ...(p.description === undefined ? {} : { description: p.description }),
        ...(p.default === undefined ? {} : { default: p.default }),
        ...(p.enum === undefined ? {} : { options: p.enum }),
      },
    ]),
  );
  const tree = treeOf(template);
  const walk = (n: unknown): unknown => {
    if (typeof n === "string")
      return n.replace(PLACEHOLDER, (_, name: string) => `$[[ inputs.${name} ]]`);
    if (Array.isArray(n)) return n.map(walk);
    if (isMap(n)) return Object.fromEntries(Object.entries(n).map(([k, v]) => [k, walk(v)]));
    return n;
  };
  const spec = { spec: { inputs } };
  const pipeline = walk(tree);
  const text = `# ${manifest.name}@${manifest.version} from ${APP_NAME}'s catalog: published as it is, edits here are overwritten by the next publish.\n${stringify(spec, WRITE)}---\n${stringify(pipeline, WRITE)}`;
  readBack(text, spec, pipeline);
  return text;
}
