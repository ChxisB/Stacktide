import { describe, expect, test } from "bun:test";
import { parse } from "yaml";
import type { Template } from "./loader";
import { manifestSchema } from "./manifest";
import { GENERATED, type Layer, RenderError, render } from "./render";

type Params = Record<string, Record<string, unknown>>;

/** A template with the given parameters (strings with a default `x` unless described) and pipeline text. */
const tpl = (pipeline: string, properties: Params = {}, required: string[] = []): Template => ({
  manifest: manifestSchema.parse({
    name: "demo",
    version: "1.2.3",
    description: "demo",
    params: { type: "object", properties, required },
  }),
  pipeline,
});
/** Any text at all: the tests that throw hostile strings at a template need a shape that lets them in. */
const ANY = "^[\\s\\S]*$";
const str = { type: "string", default: "x", pattern: ANY };
const read = (text: string) => parse(text, { version: "1.2" });
const problemsOf = (fn: () => unknown) => {
  try {
    fn();
  } catch (e) {
    expect(e).toBeInstanceOf(RenderError);
    return (e as RenderError).problems;
  }
  throw new Error("did not throw");
};

const CI = `stages: [build, test]
build:
  stage: build
  image: "{{ params.image }}"
  retry: "{{ params.retries }}"
  allow_failure: "{{ params.lenient }}"
  script:
    - echo "building {{ params.name }} on {{ params.image }}"
`;
const CI_PARAMS = {
  image: { type: "string", default: "oven/bun:1", pattern: ANY },
  retries: { type: "integer", default: 2 },
  lenient: { type: "boolean", default: false },
  name: { type: "string", default: "app", pattern: ANY },
};

describe("render", () => {
  test("every file begins with the marker that tells it from a hand-written one", () => {
    expect(render(tpl(CI, CI_PARAMS)).startsWith(`${GENERATED} demo@1.2.3.`)).toBe(true);
  });

  test("fills the placeholders with the defaults, in a fixed layout", () => {
    expect(
      render(tpl(CI, CI_PARAMS)),
    ).toBe(`# Generated by orch from template demo@1.2.3. Change the pipeline there: edits here are overwritten.
stages:
  - build
  - test
build:
  stage: build
  image: oven/bun:1
  retry: 2
  allow_failure: false
  script:
    - echo "building app on oven/bun:1"
`);
  });

  test("a placeholder that is the whole value keeps its type, one in text is text", () => {
    const out = read(render(tpl(CI, CI_PARAMS), [{ params: { retries: 5, lenient: true } }]));
    expect(out.build.retry).toBe(5);
    expect(out.build.allow_failure).toBe(true);
    const text = read(
      render(
        tpl('v: "n{{ params.n }}{{ params.b }}"\nw: "{{ params.n }}"', {
          n: { type: "integer", default: 7 },
          b: { type: "boolean", default: true },
        }),
      ),
    );
    expect(text).toEqual({ v: "n7true", w: 7 });
  });

  test("a string that looks like another type stays a string", () => {
    const out = read(render(tpl('v: "{{ params.v }}"', { v: str }), [{ params: { v: "123" } }]));
    expect(out.v).toBe("123");
  });

  test("the same input gives the same bytes, however the layers were written", () => {
    const a = render(tpl(CI, CI_PARAMS), [{ params: { image: "a", name: "n" } }]);
    const b = render(tpl(CI, CI_PARAMS), [{ params: { name: "n", image: "a" } }]);
    expect(b).toBe(a);
    expect(render(tpl(CI, CI_PARAMS), [{ params: { image: "a", name: "n" } }])).toBe(a);
  });

  test("a later layer's parameter wins, one layer at a time", () => {
    const layers: Layer[] = [
      { params: { image: "org", name: "org" } },
      { params: { image: "project" } },
      { params: { name: "env" } },
      {},
    ];
    const out = read(render(tpl(CI, CI_PARAMS), layers));
    expect(out.build.image).toBe("project");
    expect(out.build.script).toEqual(['echo "building env on project"']);
  });

  test("only values are filled: a key is written as it is", () => {
    const out = read(render(tpl('"{{ params.p }}": "{{ params.p }}"\n', { p: str })));
    expect(out).toEqual({ "{{ params.p }}": "x" });
  });

  test("an anchor is expanded where it is used, not written out again", () => {
    const text = render(tpl("base: &b {image: node}\na: *b\nb: *b\n"));
    expect(text).not.toMatch(/[&*]/);
    expect(read(text)).toEqual({
      base: { image: "node" },
      a: { image: "node" },
      b: { image: "node" },
    });
  });

  test("a long line stays one line", () => {
    const line = `echo ${"word ".repeat(60).trim()}`;
    expect(render(tpl(`script: ["${line}"]\n`))).toContain(`\n  - ${line}\n`);
  });

  test("a layer that gives a parameter no value leaves the earlier one", () => {
    const out = read(
      render(tpl(CI, CI_PARAMS), [{ params: { image: "org" } }, { params: { image: undefined } }]),
    );
    expect(out.build.image).toBe("org");
  });

  test("a parameter called __proto__ sets nothing, itself or any other", () => {
    const layer = JSON.parse('{"params": {"__proto__": {"name": "evil"}, "image": "ok"}}');
    const out = read(render(tpl(CI, CI_PARAMS), [layer]));
    expect(out.build.image).toBe("ok");
    expect(out.build.script).toEqual(['echo "building app on ok"']);
  });

  describe("overrides", () => {
    const base = tpl(`stages: [build, test]
build:
  stage: build
  script: [a, b]
  variables: {X: "1", Y: "2"}
  tags: [shared]
`);
    const over = (...overrides: NonNullable<Layer["overrides"]>[]) =>
      read(
        render(
          base,
          overrides.map((o) => ({ overrides: o })),
        ),
      );

    test("maps merge key by key, new keys come after the template's", () => {
      const out = over({
        build: { variables: { Y: "9", Z: "3" }, extra: true },
        deploy: { script: [] },
      });
      expect(out.build.variables).toEqual({ X: "1", Y: "9", Z: "3" });
      expect(Object.keys(out)).toEqual(["stages", "build", "deploy"]);
      expect(Object.keys(out.build)).toEqual(["stage", "script", "variables", "tags", "extra"]);
    });

    test("a list is replaced, not appended to, and so is a scalar", () => {
      const out = over({ build: { script: ["only"], stage: "test" }, stages: ["one"] });
      expect(out.build.script).toEqual(["only"]);
      expect(out.build.stage).toBe("test");
      expect(out.stages).toEqual(["one"]);
    });

    test("a map can be replaced by something that is not a map, and the other way round", () => {
      const out = over({ build: { variables: "none", tags: { a: 1 } } });
      expect(out.build.variables).toBe("none");
      expect(out.build.tags).toEqual({ a: 1 });
    });

    test("later layers merge over earlier ones", () => {
      const out = over(
        { build: { variables: { X: "org" } } },
        { build: { variables: { X: "env", W: "w" } } },
      );
      expect(out.build.variables).toEqual({ X: "env", Y: "2", W: "w" });
    });

    test("an override is literal text: it has no placeholders", () => {
      const withParam = tpl('a: "{{ params.p }}"\n', { p: str });
      const out = read(
        render(withParam, [{ params: { p: "v" }, overrides: { b: "{{ params.p }}" } }]),
      );
      expect(out).toEqual({ a: "v", b: "{{ params.p }}" });
    });

    test("a key called __proto__ is only a key", () => {
      const out = JSON.parse('{"__proto__": {"polluted": true}, "ok": 1}');
      try {
        render(base, [{ overrides: out }]);
      } catch (e) {
        expect(e).toBeInstanceOf(RenderError);
      }
      expect(({} as Record<string, unknown>).polluted).toBeUndefined();
    });
  });

  describe("a value is inert", () => {
    const hostile = [
      "x\n  evil:\n    script: [rm -rf /]",
      "x\nevil: {script: [rm]}",
      "- a\n- b",
      "{a: b}",
      "[a, b]",
      "*alias",
      "&anchor value",
      "!!str tagged",
      "!reference [a, b]",
      "key: value",
      "# comment",
      "a: 1 #c\nb: 2",
      "---\nb: 2",
      "...",
      "|\n  block",
      "{{ params.name }}",
      '"; rm -rf /; "',
      "yes",
      "No",
      "on",
      "null",
      "~",
      "true",
      "123",
      "1_000",
      "1:30",
      "0x1f",
      "2026-01-01",
      "2026-01-01 10:00:00",
      "1e3",
      ".inf",
      "",
      " ",
      "  lead",
      "trail  ",
      "line\r\nbreak",
      "tab\tinside",
      "é😀 end",
    ];
    const jobs = tpl(
      'build:\n  image: "{{ params.v }}"\n  script:\n    - "echo {{ params.v }}"\n    - "{{ params.v }}"\n',
      { v: { type: "string", default: "x", maxLength: 100, pattern: ANY } },
    );

    test.each(hostile)("%j stays one string in every place it is used", (v) => {
      const text = render(jobs, [{ params: { v } }]);
      for (const version of ["1.1", "1.2"] as const) {
        expect(parse(text, { version, merge: true })).toEqual({
          build: { image: v, script: [`echo ${v}`, v] },
        });
      }
    });

    test("random strings either come back the same in YAML 1.1 and 1.2, or are refused", () => {
      let seed = 42;
      const next = () => {
        seed = (Math.imul(seed, 1103515245) + 12345) & 0x7fffffff;
        return seed;
      };
      const alphabet = [..."ab 1 .:-#&*!%@`'\"{}[]|>?,=~\n\t\\0xyYnNoO_é"];
      let refused = 0;
      for (let i = 0; i < 400; i++) {
        const v = Array.from(
          { length: next() % 12 },
          () => alphabet[next() % alphabet.length],
        ).join("");
        try {
          const text = render(jobs, [{ params: { v } }]);
          for (const version of ["1.1", "1.2"] as const)
            expect(parse(text, { version, merge: true }).build.image).toBe(v);
        } catch (e) {
          expect(e).toBeInstanceOf(RenderError);
          refused++;
        }
      }
      expect(refused).toBeLessThan(40);
    });

    test("a value one reader would take for a number is refused, and no value is echoed", () => {
      const problems = problemsOf(() => render(jobs, [{ params: { v: "0o17" } }]));
      expect(problems).toEqual([
        "a value cannot be written so that every YAML reader sees the same",
      ]);
    });
  });

  describe("refuses", () => {
    const one = tpl('a: "{{ params.p }}"\n', { p: { type: "string", pattern: "^[a-z]+$" } }, ["p"]);

    test("a required parameter nobody gave", () => {
      expect(problemsOf(() => render(one))).toEqual([
        "param p: Invalid input: expected string, received undefined",
      ]);
    });

    test("a parameter that is not declared, and one of the wrong shape", () => {
      expect(problemsOf(() => render(one, [{ params: { p: "ok", q: 1 } }]))).toEqual([
        'params: Unrecognized key: "q"',
      ]);
      expect(problemsOf(() => render(one, [{ params: { p: "NO" } }]))[0]).toStartWith("param p: ");
    });

    test("a value the manifest's limits refuse never appears in the message", () => {
      const secret = "ghp_SECRETSECRET1234";
      const text = problemsOf(() => render(one, [{ params: { p: secret } }])).join("\n");
      expect(text).not.toContain(secret);
    });

    test("an optional parameter with no default that nobody gave", () => {
      const open = tpl('a: "{{ params.p }}"\nb: "{{ params.p }}"\n', {
        p: { type: "string", pattern: ANY },
      });
      expect(problemsOf(() => render(open))).toEqual(["param p: has no value and no default"]);
    });

    test.each([
      ["an unknown key", { values: {} }, "layer 0: (root): Unrecognized key"],
      ["params that are not a map", { params: ["a"] }, "layer 0: params"],
      ["an override that is not JSON", { overrides: { a: new Date() } }, "layer 0: overrides.a"],
      ["an override that holds undefined", { overrides: { a: undefined } }, "layer 0: overrides.a"],
    ])("a layer with %s", (_, layer, why) => {
      expect(problemsOf(() => render(tpl("a: 1\n"), [layer as Layer]))[0]).toStartWith(why);
    });

    test("every problem in one pass, with the layer's place", () => {
      const problems = problemsOf(() =>
        render(one, [
          { params: { p: "ok" } },
          { overrides: { a: new Date() } } as unknown as Layer,
          { nope: 1 } as Layer,
        ]),
      );
      expect(problems.map((p) => p.split(":")[0])).toEqual(["layer 1", "layer 2"]);
    });

    test("a pipeline that cannot be read", () => {
      expect(problemsOf(() => render(tpl("a: 1\na: 2\n")))[0]).toStartWith(
        "pipeline.yml: Map keys must be unique",
      );
    });
  });

  test("changes neither the template nor the layers", () => {
    const template = tpl(CI, CI_PARAMS);
    const layers: Layer[] = [{ params: { image: "a" }, overrides: { build: { script: ["x"] } } }];
    const before = JSON.stringify([template, layers]);
    render(template, layers);
    expect(JSON.stringify([template, layers])).toBe(before);
  });
});
