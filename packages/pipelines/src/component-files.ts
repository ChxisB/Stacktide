import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { APP_NAME } from "@orch/core";
import { componentFile, componentPath, validateCatalogLayout } from "./component";
import { byVersion, loadTemplates, type Template } from "./loader";

/** What the catalog project's description must say: GitLab will not list a project without one (it is a setting, not a file). */
export const CATALOG_DESCRIPTION = `CI/CD components generated by ${APP_NAME}: one per pipeline template.`;

/** The release job GitLab's Catalog needs: a release on a semver tag, and only on one (not `v1.0.0`, `1.0` or a branch). */
export const RELEASE_CI = `# Generated by ${APP_NAME}. Publishes the components to the CI/CD Catalog when a semver tag (1.2.3) is pushed.
create-release:
  stage: deploy
  image: registry.gitlab.com/gitlab-org/release-cli:latest
  script: echo "Releasing $CI_COMMIT_TAG"
  rules:
    - if: $CI_COMMIT_TAG =~ /^\\d+\\.\\d+\\.\\d+$/
  release:
    tag_name: $CI_COMMIT_TAG
    description: "Release $CI_COMMIT_TAG of the components of $CI_PROJECT_PATH"
`;

/** The newest version of each template: a catalog project holds one version of each, its tag is the component's version. */
export function latestVersions(templates: readonly Template[]): Template[] {
  const latest = new Map<string, Template>();
  for (const t of templates) {
    const have = latest.get(t.manifest.name);
    if (!have || byVersion(have.manifest.version, t.manifest.version) < 0)
      latest.set(t.manifest.name, t);
  }
  return [...latest.values()].sort((a, b) => a.manifest.name.localeCompare(b.manifest.name));
}

export function catalogReadme(templates: readonly Template[]): string {
  const rows = templates.map(({ manifest: m }) => {
    const inputs = Object.keys(m.params.properties);
    return `| \`${m.name}\` | ${m.version} | ${inputs.length === 0 ? "none" : inputs.map((i) => `\`${i}\``).join(", ")} |`;
  });
  return `# CI/CD components

Generated by ${APP_NAME} from its pipeline templates. Edits here are overwritten by the next run of \`bun run templates:component\`.

| Component | Template version | Inputs |
|---|---|---|
${rows.join("\n")}

## Use

\`\`\`yaml
include:
  - component: $CI_SERVER_FQDN/<this project's path>/<component>@<version>
    inputs: {}
\`\`\`

\`<version>\` is a release of this project: \`1.2.3\`, or a full commit SHA. Prefer those to \`1\`, \`1.2\`, \`~latest\` or a branch, which move without a change in the project that uses them.

## Publish

1. Set the project's description (the Catalog lists no project without one): "${CATALOG_DESCRIPTION}"
2. Settings > General > Visibility: turn on **CI/CD Catalog project**.
3. Push a semver tag (\`1.0.0\`). The release job in \`.gitlab-ci.yml\` creates the release and lists the version in the Catalog.
`;
}

/**
 * Writes a catalog-ready project under `dir` (CMP-3): `templates/<name>.yml` for the newest version of
 * each template, a `README.md` and the `.gitlab-ci.yml` with the release job. Returns the paths. The
 * layout is checked before anything is written, which also keeps a path inside `dir`: a component
 * name is lowercase letters, digits, `-` and `_`. The platform never writes the catalog project: a
 * person commits these files there, sets its description and tags a release.
 */
export async function writeCatalogProject(dir: string, templates: readonly Template[]) {
  const latest = latestVersions(templates);
  const files: Record<string, string> = {
    "README.md": catalogReadme(latest),
    ".gitlab-ci.yml": RELEASE_CI,
    ...Object.fromEntries(latest.map((t) => [componentPath(t.manifest), componentFile(t)])),
  };
  const problems = validateCatalogLayout(files, CATALOG_DESCRIPTION);
  if (problems.length > 0) throw new Error(`not a catalog project:\n${problems.join("\n")}`);
  const paths = Object.keys(files).sort();
  for (const path of paths) {
    await mkdir(dirname(join(dir, path)), { recursive: true });
    await writeFile(join(dir, path), files[path] ?? "");
  }
  return paths;
}

if (import.meta.main) {
  const dir = process.argv[2];
  if (!dir) {
    console.error("usage: bun run templates:component <directory>");
    process.exit(2);
  }
  for (const path of await writeCatalogProject(dir, await loadTemplates())) console.log(path);
}
