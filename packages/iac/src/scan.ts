import {
  type ApplyOn,
  MARKER,
  MAX_MANIFEST_BYTES,
  parseManifest,
  type StateStore,
  type Tool,
} from "./stack";

/** What the scanner needs of a repository: its file paths and the text of a file. */
export interface RepoSource {
  /** Every file (not directory) in the tree, as a repository-relative path with `/` separators. */
  files(): AsyncIterable<string>;
  /** The text of a file; rejects when it cannot be read. */
  read(path: string): Promise<string>;
}

/**
 * Where the stack keeps its state: `http` is what the platform wires up (D9); `other` is another
 * backend; `none` is local state, which a CI job throws away; `unchecked` is a tool whose backend
 * is generated by its own config (Terragrunt), which is not read here.
 */
export type Backend = "http" | "other" | "none" | "unchecked";

export interface Stack {
  name: string;
  /** The stack's directory, relative to the repository root (`.` for the root). */
  path: string;
  tool: Tool;
  version: string | null;
  tags: string[];
  dependsOn: string[];
  watch: string[];
  applyOn: ApplyOn;
  /** The platform environment whose variables the plan gets as `TF_VAR_*`; none: it gets none. */
  environment?: string | undefined;
  /** The worker pool the file names; none: the organization's default, if it has one (see `resolvePool`). */
  pool?: string | undefined;
  /** Where the state lives; none: GitLab's (see `usesPlatformState`). */
  state?: StateStore | undefined;
  /** How often the platform checks the stack for drift, in seconds; none: it does not. */
  driftEverySeconds?: number | undefined;
  backend: Backend;
}

export type ProblemKind =
  | "invalid-manifest"
  | "duplicate-name"
  | "missing-backend"
  | "unsafe-path"
  | "too-large"
  | "unreadable"
  | "too-many";

export interface Problem {
  kind: ProblemKind;
  /** An error leaves the stack out; a warning leaves it in. */
  severity: "error" | "warning";
  path: string;
  message: string;
}

export interface ScanOptions {
  maxStacks?: number;
  concurrency?: number;
}

// shortcut: only the first 500 markers are read, and only the first 50 `.tf` files of a stack are
// searched for the backend (`.tf.json` is not); upgrade when a repository really holds more than that.
const MAX_STACKS = 500;
const MAX_TF_FILES = 50;
const CONCURRENCY = 8;

// A stack's directory goes into shell commands and job names of generated pipelines: no spaces,
// quotes or anything a shell treats specially, and no segment that reads as an option.
const SEGMENT = /^[A-Za-z0-9._@+=][A-Za-z0-9._@+=-]*$/;
export const safeDir = (dir: string) =>
  dir === "." || dir.split("/").every((s) => s !== "." && s !== ".." && SEGMENT.test(s));

const dirOf = (path: string) => (path.includes("/") ? path.slice(0, path.lastIndexOf("/")) : ".");
const baseOf = (path: string) => path.slice(path.lastIndexOf("/") + 1);

// One left-to-right pass: a comment or a string literal is consumed whole, so a `/*` inside a string
// (an ARN such as "bucket/*") starts no comment and a `backend` inside a comment or string counts for
// nothing. Only the last alternative captures. shortcut: a regex, not an HCL parser, so a heredoc
// holding text that looks like a backend block is misread; upgrade to a parse if a false result shows.
const TOKEN = /\/\*[\s\S]*?\*\/|(?:#|\/\/).*$|"(?:[^"\\\n]|\\.)*"|\bbackend\s+"([^"\n]*)"\s*\{/gm;

/** The backend a stack's `.tf` files declare. A commented-out block does not count. */
export function backendOf(texts: string[]): Backend {
  const kinds = texts.flatMap((t) =>
    Array.from(t.matchAll(TOKEN), (m) => m[1]).filter((k) => k !== undefined),
  );
  if (kinds.includes("http")) return "http";
  return kinds.length > 0 ? "other" : "none";
}

const cmp = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

async function mapLimit<T, R>(items: T[], limit: number, fn: (item: T) => Promise<R>) {
  const out = new Array<R>(items.length);
  let next = 0;
  const worker = async () => {
    while (next < items.length) {
      const i = next++;
      out[i] = await fn(items[i] as T);
    }
  };
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker));
  return out;
}

/**
 * Finds the stacks in a repository: every directory holding a `stack.yml`. Bad markers, names two
 * stacks claim and stacks without the platform's state backend come back as problems, so one bad
 * stack never hides the others. Stacks may nest: each is its own directory, and a file belongs to
 * the innermost one (change detection decides that, not this).
 */
export async function scanStacks(source: RepoSource, options: ScanOptions = {}) {
  const maxStacks = options.maxStacks ?? MAX_STACKS;
  const concurrency = options.concurrency ?? CONCURRENCY;
  const markers: string[] = [];
  const tfByDir = new Map<string, string[]>();
  for await (const path of source.files()) {
    if (baseOf(path) === MARKER) markers.push(path);
    else if (path.endsWith(".tf")) {
      const dir = dirOf(path);
      const list = tfByDir.get(dir);
      if (list) list.push(path);
      else tfByDir.set(dir, [path]);
    }
  }
  markers.sort();

  const head: Problem[] = [];
  if (markers.length > maxStacks) {
    head.push({
      kind: "too-many",
      severity: "error",
      path: "",
      message: `${markers.length} stacks found; only the first ${maxStacks} are read`,
    });
  }

  const found = await mapLimit(markers.slice(0, maxStacks), concurrency, async (marker) => {
    const mine: Problem[] = [];
    const problem = (
      kind: ProblemKind,
      severity: Problem["severity"],
      path: string,
      message: string,
    ) => mine.push({ kind, severity, path, message });
    const dir = dirOf(marker);
    if (!safeDir(dir)) {
      problem(
        "unsafe-path",
        "error",
        marker,
        "the directory has characters a stack path may not have",
      );
      return { problems: mine };
    }
    let text: string;
    try {
      text = await source.read(marker);
    } catch {
      problem("unreadable", "error", marker, `${MARKER} could not be read`);
      return { problems: mine };
    }
    if (Buffer.byteLength(text) > MAX_MANIFEST_BYTES) {
      problem("too-large", "error", marker, `${MARKER} is larger than ${MAX_MANIFEST_BYTES} bytes`);
      return { problems: mine };
    }
    const parsed = parseManifest(text);
    if (!parsed.ok) {
      problem("invalid-manifest", "error", marker, `${MARKER}: ${parsed.errors.join("; ")}`);
      return { problems: mine };
    }
    const m = parsed.manifest;

    let backend: Backend = "unchecked";
    if (m.tool !== "terragrunt") {
      const texts: string[] = [];
      for (const file of (tfByDir.get(dir) ?? []).sort().slice(0, MAX_TF_FILES)) {
        try {
          texts.push(await source.read(file));
        } catch {
          problem(
            "unreadable",
            "warning",
            file,
            `${file} could not be read, so the backend may be misjudged`,
          );
        }
      }
      backend = backendOf(texts);
      if (backend !== "http") {
        problem(
          "missing-backend",
          "warning",
          dir,
          backend === "other"
            ? `stack "${m.name}" declares a backend other than backend "http" {}, so the platform cannot wire its state`
            : `stack "${m.name}" has no backend "http" {}: its state would be local, and a CI job loses it`,
        );
      }
    }
    const stack: Stack = {
      name: m.name,
      path: dir,
      tool: m.tool,
      version: m.version ?? null,
      tags: m.tags,
      dependsOn: m.depends_on,
      watch: m.watch,
      applyOn: m.apply_on,
      environment: m.environment,
      pool: m.pool,
      state: m.state,
      driftEverySeconds: m.drift_every,
      backend,
    };
    return { stack, problems: mine };
  });

  const candidates = found.flatMap((f) => (f.stack ? [f.stack] : []));
  // a name two directories claim cannot be addressed: neither is returned
  const byName = Object.groupBy(candidates, (s) => s.name);
  const stacks: Stack[] = [];
  const problems = [...head];
  const dropped = new Set<Stack>();
  for (const [name, group] of Object.entries(byName)) {
    if (!group) continue;
    if (group.length === 1) stacks.push(...group);
    else {
      for (const g of group) dropped.add(g);
      const where = group.map((s) => s.path);
      problems.push({
        kind: "duplicate-name",
        severity: "error",
        path: where[0] ?? "",
        message: `the name "${name}" is used by ${where.join(", ")}`,
      });
    }
  }
  // a stack's warnings go with it when it is dropped; what could not be read as a stack has errors only
  for (const f of found) {
    if (!(f.stack && dropped.has(f.stack))) problems.push(...f.problems);
  }
  stacks.sort((a, b) => cmp(a.path, b.path));
  problems.sort((a, b) => cmp(a.path, b.path) || cmp(a.kind, b.kind) || cmp(a.message, b.message));
  // only a scan with no error says every stack in the repository was read: the others may have been
  // left out for a reason that is not "the stack is gone"
  return { stacks, problems, complete: problems.every((p) => p.severity !== "error") };
}
