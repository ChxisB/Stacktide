/** A directory with a fake `curl` and a fake `docker` first on the PATH, and the files they write. */
async function bench(
  planJson: unknown = { action: "plan", levels: [] },
  exchange: unknown = {
    token: "orch_T0KEN",
    type: "Bearer",
    organizationId: ORG,
    projectId: PROJECT,
  },
) {
  const dir = await mkdtemp(join(tmpdir(), "orch-stack-workflow-"));
  scratch.push(dir);
  const bin = join(dir, "bin");
  await Bun.$`mkdir ${bin}`;
  await writeFile(join(dir, "plan.json"), JSON.stringify(planJson));
  await writeFile(join(dir, "exchange.json"), JSON.stringify(exchange));
  const sh = (body: string) => `#!/bin/bash\n${body}\n`;
  // one line per call: its arguments, tab separated
  await writeFile(
    join(bin, "curl"),
    sh(`printf '%s\\n' "$*" >> "$BENCH/curl.log"
case "$*" in
  *audience=*) [ -z "$FAKE_NO_VALUE" ] || { echo '{}'; exit 0; }
  all="$*"; aud="\${all##*audience=}"; aud="\${aud%% *}"; printf '{"value":"jwt.%s.sig"}' "$aud" ;;
  *auth/ci/exchange*) cat > "$BENCH/exchange.body"; cat "$BENCH/exchange.json" ;;
  */plan*) cat "$BENCH/plan.json" ;;
  *) echo "unexpected curl: $*" >&2; exit 22 ;;
esac`),
  );
  await writeFile(
    join(bin, "docker"),
    sh(`n=$(( $(cat "$BENCH/docker.count" 2>/dev/null || echo 0) + 1 )); echo $n > "$BENCH/docker.count"
{ printf '%s\\n' "$@"; } > "$BENCH/docker.$n.args"
env | grep -E '^(ORCH_ID_TOKEN|AWS_ID_TOKEN)=' > "$BENCH/docker.$n.env" || :
envfile=""; prev=""; for a in "$@"; do [ "$prev" = "--env-file" ] && envfile="$a"; prev="$a"; done
[ -z "$envfile" ] || cat "$envfile" > "$BENCH/docker.$n.envfile"
v="FAKE_DOCKER_EXIT_$n"; exit "\${!v:-0}"`),
  );
  await chmod(join(bin, "curl"), 0o755);
  await chmod(join(bin, "docker"), 0o755);
  const run = async (script: string, env: Record<string, string>) => {
    const out = join(dir, "github-output");
    await writeFile(out, "");
    const p = Bun.spawn(["bash", "-c", script], {
      cwd: dir,
      env: {
        PATH: `${bin}:/usr/bin:/bin`,
        BENCH: dir,
        GITHUB_OUTPUT: out,
        ACTIONS_ID_TOKEN_REQUEST_URL: "https://actions.test/token?api-version=2.0",
        ACTIONS_ID_TOKEN_REQUEST_TOKEN: "request-token",
        ...env,
      },
      stdout: "pipe",
      stderr: "pipe",
    });
    const [stdout, stderr, code] = await Promise.all([
      new Response(p.stdout).text(),
      new Response(p.stderr).text(),
      p.exited,
    ]);
    return { stdout, stderr, code, dir };
  };
  const read = (f: string) => readFile(join(dir, f), "utf8").catch(() => "");
  return { run, read, dir };
}

