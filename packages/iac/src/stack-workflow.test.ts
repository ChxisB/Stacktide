// FRG-18, FRG-29: the static stack workflow (`.github/workflows/orch-stacks.yml`) and what a run may ask of it. GitHub cannot
// be handed a generated pipeline, so the file is fixed and reads its plan from the platform (FRG-17). An apply plans again on
// the commit that was judged, in an environment whose reviewers must let it start, and applies only the changes that were judged.

const PLATFORM = { apiUrl: "https://orch.example.com", audience: "orch.example.com" };
const workflow = renderStackWorkflow(PLATFORM);

interface Step {
  uses?: string;
  run?: string;
  env?: Record<string, string>;
  with?: Record<string, unknown>;
}
interface Job {
  name?: string;
  environment?: string;
  needs?: string | string[];
  if?: string;
  "runs-on": string;
  "timeout-minutes"?: number;
  outputs?: Record<string, string>;
  permissions?: Record<string, string>;
  strategy?: { "fail-fast": boolean; matrix: { stack: string } };
  steps: Step[];
}
interface Doc {
  name: string;
  "run-name": string;
  on: {
    workflow_dispatch: {
      inputs: Record<
        string,
        { required: boolean; type: string; options?: string[]; default?: string }
      >;
    };
  };
  permissions: Record<string, string>;
  jobs: Record<string, Job>;
}
// YAML 1.1 reads a bare `on` as true; the file quotes it, and this reads it back the way GitHub and the other readers do
const doc = parse(workflow, { version: "1.1" }) as Doc;
const other = parse(workflow, { version: "1.2" }) as Doc;
const levelJobs = Array.from({ length: STACK_WORKFLOW_LEVELS }, (_, i) => `level-${i}`);
const applyJobs = Array.from({ length: STACK_WORKFLOW_LEVELS }, (_, i) => `apply-${i}`);

const stack = (name: string, over: Partial<Stack> = {}): Stack => ({
  name,
  path: `stacks/${name}`,
  tool: "terraform",
  version: "1.9.8",
  tags: [],
  dependsOn: [],
  watch: [],
  applyOn: "command",
  backend: "http",
  ...over,
});
// net <- db <- app, net <- queue
const STACKS = [
  stack("app", { dependsOn: ["db"] }),
  stack("db", { dependsOn: ["net"] }),
  stack("net"),
  stack("queue", { dependsOn: ["net"], tool: "tofu", version: "1.8.2" }),
];
const plan = (over: Partial<PlanInput> = {}): PlanInput => ({
  action: "plan",
  stacks: STACKS,
  select: ["app", "db", "net", "queue"],
  audience: PLATFORM.audience,
  apiUrl: PLATFORM.apiUrl,
  summaryPath: "/runs/0b9e5bd2/plan-summary",
  helperImage: "registry.example.com/orch/ci-helper:1.0.0",
  images: {
    terraform: "registry.example.com/tf-orch",
    tofu: "registry.example.com/tofu-orch",
    dnscontrol: "registry.example.com/dns-orch",
  },
  ...over,
});
const problemsOf = (fn: () => unknown) => {
  try {
    fn();
  } catch (e) {
    expect(e).toBeInstanceOf(GenerateError);
    return (e as GenerateError).problems;
  }
  throw new Error("did not throw");
};

describe("the file", () => {
  test("is where the onboarding puts it, and is the same for every run: a snapshot", () => {
    expect(STACK_WORKFLOW_FILE).toBe(".github/workflows/orch-stacks.yml");
    expect(workflow).toMatchSnapshot();
  });

  test("is read the same by YAML 1.1 and 1.2, and begins as a file of ours does", () => {
    expect(other).toEqual(doc);
    expect(workflow.startsWith("# Generated by orch")).toBe(true);
  });

  test("takes the run's id and what to do with it, and the run is named by both so the platform can find it", () => {
    expect(doc.on.workflow_dispatch.inputs).toEqual({
      run_id: expect.objectContaining({ required: true, type: "string" }),
      action: expect.objectContaining({
        required: false,
        type: "choice",
        options: ["plan", "apply"],
        default: "plan",
      }),
    });
    expect(Object.keys(doc.on)).toEqual(["workflow_dispatch"]);
    expect(doc["run-name"]).toBe("orch ${{ inputs.run_id }} ${{ inputs.action }}");
    // the platform finds a run by the name it expects the file to give it
    expect(doc["run-name"]).toBe(
      stackRunName("${{ inputs.run_id }}", "${{ inputs.action }}" as "plan"),
    );
  });

  test("reads the repository, and signs in to the platform with the run's own identity token", () => {
    expect(doc.permissions).toEqual({ contents: "read", "id-token": "write" });
    for (const job of Object.values(doc.jobs)) expect(job.permissions).toBeUndefined();
  });

  test("is a fetch job, then one matrix job per level to plan it and one to apply it, each after the one before", () => {
    expect(Object.keys(doc.jobs)).toEqual(["fetch", ...levelJobs, ...applyJobs]);
    levelJobs.forEach((name, i) => {
      const job = doc.jobs[name] as Job;
      expect(job.needs).toEqual(i === 0 ? "fetch" : ["fetch", `level-${i - 1}`]);
      expect(job.if).toBe(
        `needs.fetch.outputs.action == 'plan' && needs.fetch.outputs.level${i} != '[]'`,
      );
      expect(job.strategy).toEqual({
        "fail-fast": false,
        matrix: { stack: `\${{ fromJSON(needs.fetch.outputs.level${i}) }}` },
      });
      expect(job.name).toBe("plan:${{ matrix.stack.name }}");
    });
    expect(Object.keys((doc.jobs.fetch as Job).outputs ?? {})).toEqual([
      ...levelJobs.map((_, i) => `level${i}`),
      "action",
      "sha",
    ]);
  });

  test("an apply job per level waits in the environment, runs only for an apply, and the plan jobs only for a plan", () => {
    applyJobs.forEach((name, i) => {
      const job = doc.jobs[name] as Job;
      expect(job.needs).toEqual(i === 0 ? "fetch" : ["fetch", `apply-${i - 1}`]);
      expect(job.if).toBe(
        `needs.fetch.outputs.action == 'apply' && needs.fetch.outputs.level${i} != '[]'`,
      );
      expect(job.strategy).toEqual({
        "fail-fast": false,
        matrix: { stack: `\${{ fromJSON(needs.fetch.outputs.level${i}) }}` },
      });
      expect(job.name).toBe("apply:${{ matrix.stack.name }}");
    });
  });

  test("only an apply job names an environment, and as a plain name that no expression can change", () => {
    expect(APPLY_ENVIRONMENT).toBe("orch-apply");
    expect(APPLY_ENVIRONMENT).toMatch(/^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/);
    for (const [name, job] of Object.entries(doc.jobs)) {
      expect(job.environment, name).toBe(applyJobs.includes(name) ? APPLY_ENVIRONMENT : undefined);
    }
  });

  test("an apply runs the commit that was judged, a plan the one it was dispatched on", () => {
    for (const name of applyJobs) {
      const checkout = doc.jobs[name]?.steps.find((s) => s.uses?.startsWith("actions/checkout@"));
      expect(checkout?.with).toEqual({
        ref: "${{ needs.fetch.outputs.sha }}",
        "persist-credentials": false,
      });
    }
    for (const name of levelJobs) {
      const checkout = doc.jobs[name]?.steps.find((s) => s.uses?.startsWith("actions/checkout@"));
      expect(checkout?.with).toEqual({ "persist-credentials": false });
    }
  });

  test("a job is cut off after an hour, as one on the platform's state is on GitLab", () => {
    for (const name of [...levelJobs, ...applyJobs]) {
      expect(doc.jobs[name]?.["timeout-minutes"]).toBe(60);
    }
  });

  test("every action is pinned to a commit, and checkout keeps no credentials", () => {
    const uses = [...workflow.matchAll(/uses: (\S+)/g)].map((m) => m[1] ?? "");
    expect(uses.length).toBeGreaterThan(0);
    for (const u of uses) expect(u, u).toMatch(/^[\w-]+\/[\w-]+@[0-9a-f]{40}$/);
    for (const name of [...levelJobs, ...applyJobs]) {
      const checkout = doc.jobs[name]?.steps.find((s) => s.uses?.startsWith("actions/checkout@"));
      expect(checkout?.with?.["persist-credentials"], name).toBe(false);
    }
  });

  test("no expression is written into a script: a value reaches it through the environment", () => {
    const scripts = Object.values(doc.jobs).flatMap((j) => j.steps.flatMap((s) => s.run ?? []));
    expect(scripts.length).toBeGreaterThan(0);
    for (const script of scripts) expect(script).not.toContain("${{");
    expect(doc.jobs.fetch?.steps[0]?.env?.RUN_ID).toBe("${{ inputs.run_id }}");
    expect(doc.jobs.fetch?.steps[0]?.env?.ACTION).toBe("${{ inputs.action }}");
  });

  test("no secret of the repository is read, and none is written to a file or an artifact", () => {
    expect(workflow).not.toContain("secrets.");
    // a plan holds the values of secrets, and a GitHub artifact is open to everyone who can read the repository
    expect(workflow).not.toContain("upload-artifact");
  });

  test("the platform's address and audience are those it was rendered for, and nothing else is", () => {
    expect(workflow).toContain(PLATFORM.apiUrl);
    expect(workflow).toContain(PLATFORM.audience);
    const again = renderStackWorkflow({
      apiUrl: "https://other.example.org:8443/orch",
      audience: "x",
    });
    expect(again).toContain("https://other.example.org:8443/orch");
    expect(again).not.toContain(PLATFORM.apiUrl);
  });

  test.each([
    [{ apiUrl: "https://orch.example.com/" }, "trailing slash"],
    [{ apiUrl: "ftp://orch.example.com" }, "scheme"],
    [{ apiUrl: 'https://orch.example.com"; curl evil' }, "quote"],
    [{ apiUrl: "https://orch.example.com/$(id)" }, "substitution"],
    [{ audience: "a b" }, "space"],
    [{ audience: "" }, "empty"],
    [{ audience: "a\nb" }, "newline"],
  ])("a platform with a bad address or audience is refused (%j: %s)", (over) => {
    const problems = problemsOf(() => renderStackWorkflow({ ...PLATFORM, ...over }));
    expect(problems).toHaveLength(1);
    expect(problems[0]).toMatch(/apiUrl|audience/);
  });
});

describe("what a run may ask of it", () => {
  test("a plan of ordinary stacks: the levels and commands are the generator's own, on the platform's state", () => {
    const got = githubRunPlan(plan());
    expect(got.levels.map((l) => l.map((s) => s.name))).toEqual([
      ["net"],
      ["db", "queue"],
      ["app"],
    ]);
    // state: orch is the default on GitHub (D9), where GitLab's managed state does not exist
    expect(got.levels.flat().map((s) => s.state)).toEqual(["orch", "orch", "orch", "orch"]);
    const orchStacks = STACKS.map((s) => ({ ...s, state: "orch" as const }));
    expect(got).toEqual(runPlan(plan({ stacks: orchStacks })));
    expect(got.levels[0]?.[0]?.jobs.plan?.commands.join("\n")).toContain("orch ci login --state");
  });

  test("a state a stack chose is left as it is: its own backend stays", () => {
    const own = [stack("a", { backend: "other" }), stack("b", { state: "orch" })];
    const got = githubRunPlan(plan({ stacks: own, select: ["a", "b"] }));
    expect(got.levels.flat().map((s) => [s.name, s.state])).toEqual([
      ["a", "own"],
      ["b", "orch"],
    ]);
  });

  test("a DNS zone is refused, naming it and why", () => {
    const zone = stack("zone", {
      tool: "dnscontrol",
      version: "5.5.0",
      path: "dns",
      backend: "unchecked",
    });
    expect(problemsOf(() => githubRunPlan(plan({ stacks: [zone], select: ["zone"] })))).toEqual([
      'stack "zone" is a DNS zone: DNSControl runs on GitLab only',
    ]);
  });

  test("a cost-gated stack is refused, naming it and why", () => {
    const input = plan({
      cost: { stacks: ["net"], image: "registry.example.com/orch/ci-cost:1.0.0" },
    });
    expect(problemsOf(() => githubRunPlan(input))).toEqual([
      'stack "net" is cost-gated: the cost estimate runs on GitLab only',
    ]);
  });

  test("a stack on a worker pool is refused: pools are GitLab runners", () => {
    const pool: PoolRef = {
      name: "big",
      tags: ["big-runner"],
      image: null,
      enabled: true,
      isDefault: false,
    };
    const stacks = [stack("queue", { pool: "big" })];
    const problems = problemsOf(() =>
      githubRunPlan(plan({ stacks, select: ["queue"], pools: [pool] })),
    );
    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain('stack "queue"');
    expect(problems[0]).toContain("worker pool");
  });

  test("a stack on GitLab's managed state is refused", () => {
    const stacks = [stack("net", { state: "gitlab" })];
    expect(problemsOf(() => githubRunPlan(plan({ stacks, select: ["net"] })))).toEqual([
      'stack "net" keeps its state in GitLab\'s managed state, which GitHub does not have',
    ]);
  });

  test("a stack that reads an environment's variables is refused: a GitHub job has an environment only by deploying", () => {
    const stacks = [stack("app", { environment: "prod" })];
    const problems = problemsOf(() => githubRunPlan(plan({ stacks, select: ["app"] })));
    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain('stack "app"');
    expect(problems[0]).toContain('environment "prod"');
  });

  test("a stack judged by policy is refused: its sets are fetched from GitLab", () => {
    const set: PolicySet = {
      name: "prod-rules",
      source: "platform/policies",
      ref: "v1.2.0",
      path: ".",
      tag: "prod",
    };
    const stacks = [stack("net", { tags: ["prod"] })];
    const input = plan({
      stacks,
      select: ["net"],
      policy: {
        sets: [set],
        image: "registry.example.com/orch/ci-policy:1.0.0",
        path: "/runs/1/policy",
      },
    });
    const problems = problemsOf(() => githubRunPlan(input));
    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain('stack "net"');
    expect(problems[0]).toContain("summary job");
    expect(problems[0]).toContain("CI_JOB_TOKEN");
  });

  test("every stack that cannot run is named, in one answer", () => {
    const stacks = [
      stack("zone", { tool: "dnscontrol", version: "5.5.0", path: "dns", backend: "unchecked" }),
      stack("app", { environment: "prod" }),
      stack("net"),
    ];
    const problems = problemsOf(() =>
      githubRunPlan(plan({ stacks, select: ["zone", "app", "net"] })),
    );
    expect(problems.join("\n")).toContain('stack "zone"');
    expect(problems.join("\n")).toContain('stack "app"');
    expect(problems.join("\n")).not.toContain('stack "net"');
  });

  test("a graph deeper than the file has room for is refused with both numbers", () => {
    const n = STACK_WORKFLOW_LEVELS + 1;
    const chain = Array.from({ length: n }, (_, i) =>
      stack(`s${i}`, { dependsOn: i === 0 ? [] : [`s${i - 1}`] }),
    );
    const select = chain.map((s) => s.name);
    expect(problemsOf(() => githubRunPlan(plan({ stacks: chain, select })))).toEqual([
      `the stacks run in ${n} levels; the workflow has room for ${STACK_WORKFLOW_LEVELS}`,
    ]);
    // and as many as it has room for are not
    const fits = chain.slice(0, STACK_WORKFLOW_LEVELS);
    expect(
      githubRunPlan(plan({ stacks: fits, select: fits.map((s) => s.name) })).levels,
    ).toHaveLength(STACK_WORKFLOW_LEVELS);
  });

  test("what the generator refuses is refused with its own problems", () => {
    expect(problemsOf(() => githubRunPlan(plan({ select: ["nope"] })))[0]).toContain(
      "unknown stack",
    );
  });

  test("the plan holds no value: variable names and references only", () => {
    const text = JSON.stringify(
      githubRunPlan(plan({ cloudTokens: { AWS_ID_TOKEN: "sts.amazonaws.com" } })),
    );
    expect(text).toContain("$ORCH_STATE_TOKEN");
    expect(text).not.toMatch(/ghp_|ghs_|eyJ/);
  });
});

describe("what an apply may ask of it", () => {
  const SHA = "0123456789abcdef0123456789abcdef01234567";
  const none = { add: 0, change: 0, destroy: 0, resources: [] };
  const apply = (over: Partial<GithubApplyInput> = {}): GithubApplyInput => ({
    ...plan(),
    action: "apply",
    sha: SHA,
    judged: Object.fromEntries(
      STACKS.map((s) => [
        s.name,
        { ...none, add: 1, resources: [{ address: `x.${s.name}`, actions: ["create"] }] },
      ]),
    ),
    ...over,
  });
  const orchStacks = STACKS.map((s) => ({ ...s, state: "orch" as const }));

  test("the levels of the plan, each stack with its plan job and an apply job, the commit and what was judged", () => {
    const input = apply();
    const got = githubRunPlan(input);
    expect(runPlanSchema.parse(got)).toEqual(got);
    expect(got.action).toBe("apply");
    expect(got.sha).toBe(SHA);
    const asPlan = githubRunPlan(plan());
    expect(got.levels.map((l) => l.map((s) => s.name))).toEqual(
      asPlan.levels.map((l) => l.map((s) => s.name)),
    );
    for (const s of got.levels.flat()) {
      expect(Object.keys(s.jobs).sort()).toEqual(["apply", "plan"]);
      expect(s.judged).toEqual(input.judged[s.name]);
      const planJob = asPlan.levels.flat().find((p) => p.name === s.name)?.jobs.plan;
      expect(s.jobs.plan).toEqual(planJob);
    }
  });

  test("the apply job is GitLab's, less the line that downloads the plan its plan job saved", () => {
    const got = githubRunPlan(apply());
    const gitlab = runPlan({
      action: "apply",
      stacks: orchStacks,
      select: ["app", "db", "net", "queue"],
      planJobs: { app: 1, db: 2, net: 3, queue: 4 },
      images: plan().images,
      platform: PLATFORM,
    });
    const theirs = gitlab.levels.flat();
    expect(got.levels.flat()).toHaveLength(theirs.length);
    for (const s of got.levels.flat()) {
      const apply = s.jobs.apply;
      const orig = theirs.find((t) => t.name === s.name)?.jobs.apply;
      expect(apply?.commands.length).toBe((orig?.commands.length ?? 0) - 1);
      expect(apply?.commands.some((c) => c.startsWith("wget"))).toBe(false);
      if (!orig) throw new Error(`GitLab has no apply for ${s.name}`);
      expect(apply).toEqual({
        ...orig,
        commands: orig.commands.filter((c) => !c.startsWith("wget")),
      });
      // it applies the plan the plan job has just written, in the tree both run in, and holds the state's lock while it does
      const text = (apply?.commands ?? []).join("\n");
      expect(text).toContain("apply -input=false -lock-timeout=5m plan.tfplan");
      expect(text).toContain("orch ci login --state");
      expect(text).toContain("TF_HTTP_LOCK_ADDRESS");
      expect(text).not.toContain("CI_JOB_TOKEN");
    }
  });

  test("a stack on a state of its own is applied without the platform's state", () => {
    const own = [stack("a", { backend: "other", path: "." })];
    const got = githubRunPlan(apply({ stacks: own, select: ["a"], judged: { a: none } }));
    const text = (got.levels[0]?.[0]?.jobs.apply?.commands ?? []).join("\n");
    expect(text).not.toContain("orch ci login");
    expect(text).toContain("apply -input=false");
    expect(got.levels[0]?.[0]?.state).toBe("own");
  });

  test("no summary job is in an apply: the changes were posted by the plan", () => {
    for (const s of githubRunPlan(apply()).levels.flat()) expect(s.jobs.summary).toBeUndefined();
  });

  test.each([
    ["short", SHA.slice(1)],
    ["upper case", SHA.toUpperCase()],
    ["a branch", "main"],
    ["empty", ""],
    ["with a line after it", `${SHA}\nlevel0=[]`],
  ])("a commit that is %s is refused", (_, sha) => {
    expect(problemsOf(() => githubRunPlan(apply({ sha })))).toEqual([
      "sha is not a commit: 40 lower-case hexadecimal digits are needed",
    ]);
  });

  test.each([
    ["no judged changes", {}],
    ["counts that are not whole", { net: { ...none, add: 1.5 } }],
    ["a negative count", { net: { ...none, destroy: -1 } }],
    ["resources that are not a list", { net: { ...none, resources: "all" } }],
    ["a resource with no address", { net: { ...none, resources: [{ actions: ["create"] }] } }],
  ])("a stack with %s is refused, naming it", (_, judged) => {
    const problems = problemsOf(() =>
      githubRunPlan(apply({ stacks: [stack("net")], select: ["net"], judged: judged as never })),
    );
    expect(problems).toEqual(['stack "net" has no judged changes to apply']);
  });

  test("only the selected stacks need to have been judged", () => {
    const got = githubRunPlan(apply({ select: ["net"], judged: { net: none } }));
    expect(got.levels.flat().map((s) => s.name)).toEqual(["net"]);
  });

  test("what a plan refuses, an apply refuses, together with what is wrong with the apply", () => {
    const stacks = [
      stack("zone", { tool: "dnscontrol", version: "5.5.0", path: "dns", backend: "unchecked" }),
      stack("app", { environment: "prod" }),
      stack("db", { state: "gitlab" }),
    ];
    const problems = problemsOf(() =>
      githubRunPlan(apply({ stacks, select: ["zone", "app", "db"], judged: {}, sha: "main" })),
    );
    const text = problems.join("\n");
    expect(text).toContain("sha is not a commit");
    for (const name of ["zone", "app", "db"])
      expect(text).toContain(`stack "${name}" has no judged`);
    expect(text).toContain("DNS zone");
    expect(text).toContain("environment");
    expect(text).toContain("GitLab's managed state");
  });

  test("a graph deeper than the file has room for is refused for an apply too", () => {
    const n = STACK_WORKFLOW_LEVELS + 1;
    const chain = Array.from({ length: n }, (_, i) =>
      stack(`s${i}`, { dependsOn: i === 0 ? [] : [`s${i - 1}`] }),
    );
    const judged = Object.fromEntries(chain.map((s) => [s.name, none]));
    expect(
      problemsOf(() =>
        githubRunPlan(apply({ stacks: chain, select: chain.map((s) => s.name), judged })),
      ),
    ).toEqual([
      `the stacks run in ${n} levels; the workflow has room for ${STACK_WORKFLOW_LEVELS}`,
    ]);
  });

  test("the plan of an apply holds no value: variable names, references, and the addresses that were judged", () => {
    const text = JSON.stringify(
      githubRunPlan(apply({ cloudTokens: { AWS_ID_TOKEN: "sts.amazonaws.com" } })),
    );
    expect(text).toContain("$ORCH_STATE_TOKEN");
    expect(text).not.toMatch(/ghp_|ghs_|eyJ|password/);
  });

  test("a plan keeps no commit and no judged changes, so a plan of GitLab's is as it was", () => {
    const got = githubRunPlan(plan());
    expect(got.sha).toBeUndefined();
    expect(got.levels.flat().every((s) => s.judged === undefined)).toBe(true);
    expect(Object.keys(got).sort()).toEqual(["action", "levels"]);
  });
});

