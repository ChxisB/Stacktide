describe.skipIf(!tools)("an apply job's script, run with a stand-in docker", () => {
  const SECRET = "hunter2-not-for-a-log";
  const judged = {
    add: 2,
    change: 0,
    destroy: 1,
    resources: [
      { address: "aws_s3_bucket.a", actions: ["create"] },
      { address: "aws_s3_bucket.b", actions: ["delete", "create"] },
    ],
  };
  // what `terraform show -json` writes: the changes with their values, here a secret one
  const change = (address: string, actions: string[]) => ({
    address,
    change: { actions, after: { password: SECRET } },
  });
  const planned = (...changes: [string, string[]][]) => ({
    resource_changes: [
      ...changes.map(([a, actions]) => change(a, actions)),
      change("aws_vpc.main", ["no-op"]),
      change("data.aws_caller_identity.me", ["read"]),
    ],
  });
  const same = planned(["aws_s3_bucket.a", ["create"]], ["aws_s3_bucket.b", ["delete", "create"]]);
  const job = (commands: string[]) => ({
    commands,
    image: "registry.example.com/tf-orch:1.9.8",
    tags: [],
    env: {},
    idTokens: {},
    allowFailure: false,
  });
  const stackOf = (over: object = {}) =>
    JSON.stringify({
      name: "net",
      path: "stacks/net",
      jobs: { plan: job(["terraform plan"]), apply: job(["terraform apply plan.tfplan"]) },
      judged,
      ...over,
    });
  /** A bench whose plan job leaves `written` in the stack's directory, as terraform show does. */
  async function withPlan(written: unknown, at = "stacks/net") {
    const b = await bench();
    await Bun.$`mkdir -p ${join(b.dir, at)}`;
    if (written !== undefined)
      await writeFile(join(b.dir, at, "plan.json"), JSON.stringify(written));
    return b;
  }

  test("plans again, and applies when the changes are the ones that were judged", async () => {
    const b = await withPlan(same);
    const r = await b.run(applyScript, { STACK: stackOf() });
    expect(r.stderr).toBe("");
    expect(r.code).toBe(0);
    expect(await b.read("docker.count")).toBe("2\n");
    expect((await b.read("docker.1.args")).endsWith("-c\nterraform plan\n")).toBe(true);
    expect((await b.read("docker.2.args")).endsWith("-c\nterraform apply plan.tfplan\n")).toBe(
      true,
    );
  });

  test("the order of the resources does not matter, the changes do", async () => {
    const b = await withPlan({ resource_changes: [...same.resource_changes].reverse() });
    const r = await b.run(applyScript, { STACK: stackOf() });
    expect(r.code).toBe(0);
    expect(await b.read("docker.count")).toBe("2\n");
  });

  test.each([
    [
      "a resource more",
      planned(
        ["aws_s3_bucket.a", ["create"]],
        ["aws_s3_bucket.b", ["delete", "create"]],
        ["aws_iam_user.x", ["create"]],
      ),
    ],
    ["a resource fewer", planned(["aws_s3_bucket.a", ["create"]])],
    [
      "a resource of another address",
      planned(["aws_s3_bucket.a", ["create"]], ["aws_s3_bucket.c", ["delete", "create"]]),
    ],
    [
      "a resource with other actions",
      planned(["aws_s3_bucket.a", ["delete"]], ["aws_s3_bucket.b", ["delete", "create"]]),
    ],
    ["no change at all", planned()],
    ["only a resource that was not judged", planned(["aws_iam_user.x", ["create"]])],
  ])("%s: nothing is applied, and the log says to plan again", async (_, written) => {
    const b = await withPlan(written);
    const r = await b.run(applyScript, { STACK: stackOf() });
    expect(r.code).not.toBe(0);
    expect(await b.read("docker.count")).toBe("1\n");
    expect(r.stderr).toContain("net");
    expect(r.stderr).toContain("not the ones that were judged");
    expect(r.stderr).toContain("Plan again");
  });

  test("the counts are judged too, not only the list", async () => {
    const b = await withPlan(same);
    const r = await b.run(applyScript, {
      STACK: stackOf({ judged: { ...judged, destroy: 2 } }),
    });
    expect(r.code).not.toBe(0);
    expect(await b.read("docker.count")).toBe("1\n");
  });

  test("no value of the plan reaches the log, whether it is applied or not", async () => {
    for (const written of [same, planned(["aws_iam_user.x", ["create"]])]) {
      const b = await withPlan(written);
      const r = await b.run(applyScript, { STACK: stackOf() });
      expect(r.stdout + r.stderr).not.toContain(SECRET);
    }
  });

  test("a stack in the top directory has its plan read there", async () => {
    const b = await withPlan(same, ".");
    const r = await b.run(applyScript, { STACK: stackOf({ path: "." }) });
    expect(r.code).toBe(0);
    expect(await b.read("docker.count")).toBe("2\n");
  });

  test("a plan that wrote no file, or one that is not a plan, is no reason to apply", async () => {
    for (const written of [undefined, "not a plan"]) {
      const b = await withPlan(written);
      const r = await b.run(applyScript, { STACK: stackOf() });
      expect(r.code).not.toBe(0);
      expect(await b.read("docker.count")).toBe("1\n");
    }
  });

  test("a plan job that failed is not followed by an apply", async () => {
    const b = await withPlan(same);
    const r = await b.run(applyScript, { STACK: stackOf(), FAKE_DOCKER_EXIT_1: "1" });
    expect(r.code).not.toBe(0);
    expect(await b.read("docker.count")).toBe("1\n");
  });

  test.each([
    ["no judged changes", { judged: undefined }],
    ["judged changes that are not an object", { judged: "none" }],
    ["no plan job", { jobs: { apply: job(["terraform apply plan.tfplan"]) } }],
    ["no apply job", { jobs: { plan: job(["terraform plan"]) } }],
  ])("a stack with %s runs nothing at all", async (_, over) => {
    const b = await withPlan(same);
    const r = await b.run(applyScript, { STACK: stackOf(over) });
    expect(r.code).not.toBe(0);
    expect(r.stderr).toContain("nothing was applied");
    expect(await b.read("docker.count")).toBe("");
  });

  test("the comparison is the summary's own filter, which the single quotes around it cannot hold", () => {
    expect(SUMMARY_FILTER).not.toContain("'");
    expect(applyScript).toContain(SUMMARY_FILTER);
    // the plan script has no use for it
    expect(levelScript).not.toContain(SUMMARY_FILTER);
  });
});

