import { afterAll, beforeAll, expect, test } from "bun:test";
import { createGitlab } from "@orch/gitlab";
import { configure, getConfig, screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { mount, startBackend } from "./testing";
import {
  addEnvironment,
  addNew,
  cellOf,
  must,
  SECRET,
  showCompare,
  tagsOf,
} from "./variables.fixture";

// UI-9: the whole journey of a new team, in one test, through the screens and the real API, with
// the mock GitLab standing in for GitLab. (Sign-in itself is covered by the API's tests.)

const FILE = ".gitlab-ci.yml";
const PIPELINE = "stages:\n  - test\ntest:\n  stage: test\n  script:\n    - bun test\n";

const DEFAULT_BRANCH = "main";
const waited = getConfig().asyncUtilTimeout;
let backend: Awaited<ReturnType<typeof startBackend>>;
beforeAll(async () => {
  // every wait here is on a real API and a real database
  configure({ asyncUtilTimeout: 5000 });
  backend = await startBackend([
    {
      manifest: {
        name: "plain-app",
        version: "1.0.0",
        description: "A project that needs nothing but tests.",
        params: { type: "object", properties: {}, required: [] },
        detects: ["bun"],
        requiresVariables: [],
      },
      pipeline: PIPELINE,
    },
  ]);
  backend.startWorker();
});
afterAll(async () => {
  configure({ asyncUtilTimeout: waited });
  await backend.stop();
});

test("connect GitLab, import a project, set up its pipeline, give it variables and sync them", async () => {
  window.location.hash = "#/projects";
  const org = await backend.organization("Acme");
  const mock = backend.gitlab(undefined, ["api"]);
  const gl = mock.addProject({
    path: "acme/web",
    defaultBranch: DEFAULT_BRANCH,
    files: { "bun.lock": "", "package.json": "{}" },
  });
  mock.addMember({ project: gl.id }, mock.tokenUser.id, 40);
  const gitlab = createGitlab({
    baseUrl: mock.url,
    auth: { type: "private-token", token: mock.token },
    maxRetries: 0,
  });
  const admin = await backend.signIn("Journey admin", {
    orgRoles: { [org.id]: "admin" },
    projectRoles: {},
  });
  const { settled } = mount(admin.client);
  const user = userEvent.setup();
  const nav = async (page: string) =>
    user.click(
      within(await screen.findByRole("navigation", { name: "Main" })).getByRole("link", {
        name: page,
      }),
    );

  // 1. connect GitLab with a token, and import the project
  await user.click(await screen.findByRole("button", { name: "Add a connection" }));
  await user.clear(await screen.findByLabelText("GitLab address"));
  await user.type(screen.getByLabelText("GitLab address"), mock.url);
  await user.type(screen.getByLabelText("Access token"), mock.token);
  await user.click(screen.getByRole("button", { name: "Connect" }));
  await user.click(await screen.findByRole("checkbox", { name: /^acme\/web/ }));
  await user.click(screen.getByRole("button", { name: "Import 1 selected" }));
  const results = await screen.findByRole("region", { name: "Import results" });
  expect(within(results).getByRole("listitem").textContent).toContain("acme/web: created");
  expect(document.body.innerHTML).not.toContain(mock.token);

  // 2. set its pipeline up: a merge request, and nothing on the default branch
  await nav("Pipeline");
  await user.click(await screen.findByRole("button", { name: "Choose a template" }));
  await user.click(await screen.findByRole("radio", { name: /^plain-app / }));
  await user.click(screen.getByRole("button", { name: "Next" }));
  await screen.findByRole("form", { name: "Step 3: Parameters" });
  const preview = (await screen.findByRole("button", {
    name: "Preview pipeline",
  })) as HTMLButtonElement;
  await waitFor(() => expect(preview.disabled).toBe(false));
  await user.click(preview);
  await screen.findByRole("region", { name: "Step 4: Review" });
  await user.click(await screen.findByRole("button", { name: "Create merge request" }));
  const done = await screen.findByRole("region", { name: "Result" });
  expect(done.textContent).toContain("merge request !1");
  const mrs = [];
  for await (const m of gitlab.mergeRequests.list(gl.id)) mrs.push(m);
  expect(mrs.map((m) => m.sourceBranch)).toEqual(["orch/pipeline"]);
  const onBranch = await gitlab.repository.getFile(gl.id, FILE, "orch/pipeline");
  expect(onBranch.content).toContain(PIPELINE);
  expect(onBranch.content).toContain("Generated by orch from template plain-app@1.0.0");
  const onDefault = await gitlab.repository.getFile(gl.id, FILE, DEFAULT_BRANCH).catch((e) => e);
  expect(onDefault).toMatchObject({ name: "GitlabError", kind: "not_found" });

  // 3. two environments, a secret for all of them and a plain value for one
  await nav("Variables");
  for (const name of ["dev", "staging"]) {
    await addEnvironment(user, name);
    await waitFor(() => expect(screen.queryByRole("dialog") === null).toBe(true));
  }
  await settled();
  // the page opens on the Secrets list; the grid of every environment is one press away
  await showCompare();
  // the drawer, not the page: the grid has a quick-add field of its own with the same labels
  await addNew(user, "Add a variable");
  const first = within(await screen.findByRole("dialog", { name: "New variable" }));
  await user.type(first.getByLabelText("Name"), "API_KEY");
  await user.type(first.getByLabelText("Value"), SECRET);
  await user.click(first.getByRole("button", { name: "Add variable" }));
  await screen.findByRole("rowheader", { name: "API_KEY" });
  await addNew(user, "Add a variable");
  const second = within(await screen.findByRole("dialog", { name: "New variable" }));
  await user.selectOptions(second.getByLabelText("Kind"), "plain");
  await user.type(second.getByLabelText("Name"), "LOG_LEVEL");
  await user.type(second.getByLabelText("Value"), "debug");
  await user.selectOptions(second.getByLabelText("Applies to"), "Only dev");
  await user.click(second.getByRole("button", { name: "Add variable" }));
  await screen.findByRole("rowheader", { name: "LOG_LEVEL" });
  expect(tagsOf(cellOf("API_KEY", "staging"))).toEqual(["From project", "secret"]);
  expect(cellOf("LOG_LEVEL", "dev").textContent).toContain("debug");
  expect(cellOf("LOG_LEVEL", "staging").textContent).toContain("Not set");
  expect(document.body.innerHTML).not.toContain(SECRET);

  // 4. a sync target (made through the API: no screen creates one yet), then plan and apply it
  const orgScope = admin.client.organizations({ orgId: org.id });
  const [connection] = must(await orgScope.connections.get({ query: { limit: 100 } })).items;
  const [project] = must(await orgScope.projects.get({ query: { limit: 100 } })).items;
  if (!connection || !project) throw new Error("the import left no connection or project");
  must(
    await orgScope.projects({ projectId: project.id })["sync-targets"].post({
      name: "main",
      type: "gitlab-variables",
      connectionId: connection.id,
      config: { project: gl.path },
      environmentMapping: { dev: "development" },
    }),
  );
  await nav("Sync");
  await user.click(await screen.findByRole("button", { name: "Plan sync" }));
  const plan = await screen.findByRole("region", { name: "Plan for main" });
  // a plan changes nothing on the target
  const before = [];
  for await (const v of gitlab.variables.list({ project: gl.path })) before.push(v.key);
  expect(before).toEqual([]);
  await user.click(within(plan).getByRole("button", { name: "Apply…" }));
  await user.click(screen.getByRole("button", { name: "Apply plan" }));
  const card = await screen.findByRole("region", { name: "Sync target main" });
  await waitFor(() => {
    const facts = Object.fromEntries(
      Array.from(card.querySelectorAll("dt")).map((dt) => [
        dt.textContent,
        dt.nextElementSibling?.textContent,
      ]),
    );
    expect(facts["Last sync"]).toMatch(/^Applied \d{4}-/);
  });

  // 5. GitLab holds the variables, and no screen showed the secret
  const held: Record<string, string> = {};
  for await (const v of gitlab.variables.list({ project: gl.path })) {
    held[`${v.key} ${v.scope}`] = v.value ?? "";
  }
  expect(held).toEqual({ "API_KEY *": SECRET, "LOG_LEVEL development": "debug" });
  expect(document.body.innerHTML).not.toContain(SECRET);
  expect(document.body.innerHTML).not.toContain(mock.token);
}, 60_000);
