import { readFileSync } from "node:fs";
import { expect, type Locator, type Page, test } from "@playwright/test";

// UI-9: the whole journey of a new team in a real browser, through the screens and the real API, with the mock
// GitLab standing in for GitLab. The same journey runs in happy-dom as src/journey.test.tsx; this one proves the
// built page works in Chromium. (Sign-in itself is covered by the API's tests: the session is made in the database.)

const SECRET = "s3cr3t-value-9f2c41";
const PIPELINE = "stages:\n  - test\ntest:\n  stage: test\n  script:\n    - bun test\n";
type State = {
  session: string;
  org: string;
  gitlab: { url: string; token: string; projectId: number; path: string };
};
// read when the tests run, not when the file loads: `playwright test --list` loads it with no server up
const state = {} as State;
test.beforeAll(() => {
  Object.assign(state, JSON.parse(readFileSync(`${import.meta.dirname}/.state.json`, "utf8")));
});

/** A request to the mock GitLab, as the platform itself would make it. */
async function gitlab(path: string) {
  const res = await fetch(`${state.gitlab.url}/api/v4/projects/${state.gitlab.projectId}${path}`, {
    headers: { "private-token": state.gitlab.token },
  });
  return { status: res.status, body: res.ok ? await res.json() : undefined };
}

/** The cell of the variables grid for one variable in one environment. */
async function cellOf(page: Page, key: string, env: string): Promise<Locator> {
  const grid = page.getByRole("table", { name: "Variables by environment" });
  const column = (await grid.getByRole("columnheader").allTextContents()).indexOf(env);
  expect(column, `a column ${env}`).toBeGreaterThan(0);
  const row = grid.getByRole("row").filter({ has: page.getByRole("rowheader", { name: key }) });
  return row.getByRole("cell").nth(column - 1);
}

test("connect GitLab, import a project, set up its pipeline, give it variables and sync them", async ({
  page,
  context,
  baseURL,
}) => {
  await context.addCookies([{ name: "orch_session", value: state.session, url: String(baseURL) }]);
  const nav = (name: string) =>
    page.getByRole("navigation", { name: "Main" }).getByRole("link", { name }).click();
  await page.goto("/#/projects");

  // 1. connect GitLab with a token, and import the project
  await page.getByLabel("GitLab address").fill(state.gitlab.url);
  await page.getByLabel("Access token").fill(state.gitlab.token);
  await page.getByRole("button", { name: "Connect" }).click();
  await page.getByRole("checkbox", { name: /^acme\/web/ }).check();
  await page.getByRole("button", { name: "Import 1 selected" }).click();
  await expect(page.getByRole("region", { name: "Import results" })).toContainText(
    "acme/web: created",
  );
  expect(await page.content()).not.toContain(state.gitlab.token);

  // 2. set its pipeline up: a merge request, and nothing on the default branch
  await nav("Pipeline");
  await page.getByRole("button", { name: "Choose a template" }).click();
  await page.getByRole("radio", { name: /^plain-app / }).check();
  await page.getByRole("button", { name: "Next" }).click();
  await expect(page.getByRole("form", { name: "Step 3: Parameters" })).toBeVisible();
  await page.getByRole("button", { name: "Preview pipeline" }).click();
  await expect(page.getByRole("region", { name: "Step 4: Review" })).toBeVisible();
  await page.getByRole("button", { name: "Create merge request" }).click();
  await expect(page.getByRole("region", { name: "Result" })).toContainText("merge request !1");
  const mrs = (await gitlab("/merge_requests?state=all")).body as { source_branch: string }[];
  expect(mrs.map((m) => m.source_branch)).toEqual(["orch/pipeline"]);
  const file = (ref: string) => gitlab(`/repository/files/.gitlab-ci.yml?ref=${ref}`);
  const onBranch = (await file("orch/pipeline")).body as { content: string };
  const text = Buffer.from(onBranch.content, "base64").toString("utf8");
  expect(text).toContain(PIPELINE);
  expect(text).toContain("Generated by orch from template plain-app@1.0.0");
  expect((await file("main")).status).toBe(404);

  // 3. two environments, a secret for all of them and a plain value for one
  await nav("Variables");
  for (const name of ["dev", "staging"]) {
    await page.getByLabel("New environment").fill(name);
    await page.getByRole("button", { name: "Add environment" }).click();
    await expect(page.getByLabel("New environment")).toHaveValue("");
  }
  await page.getByRole("button", { name: "Add a variable" }).click();
  await page.getByLabel("Name").fill("API_KEY");
  await page.getByLabel("Value").fill(SECRET);
  await page.getByRole("button", { name: "Add variable" }).click();
  await expect(page.getByRole("rowheader", { name: "API_KEY" })).toBeVisible();
  await page.getByRole("button", { name: "Add a variable" }).click();
  await page.getByLabel("Kind").selectOption("plain");
  await page.getByLabel("Name").fill("LOG_LEVEL");
  await page.getByLabel("Value").fill("debug");
  await page.getByLabel("Applies to").selectOption({ label: "Only dev" });
  await page.getByRole("button", { name: "Add variable" }).click();
  await expect(page.getByRole("rowheader", { name: "LOG_LEVEL" })).toBeVisible();
  await expect((await cellOf(page, "API_KEY", "staging")).locator(".tag")).toHaveText([
    "From project",
    "secret",
  ]);
  await expect(await cellOf(page, "LOG_LEVEL", "dev")).toContainText("debug");
  await expect(await cellOf(page, "LOG_LEVEL", "staging")).toContainText("Not set");
  expect(await page.content()).not.toContain(SECRET);

  // 4. a sync target (made through the API: no screen creates one yet), then plan and apply it
  const api = async (path: string) => {
    const res = await page.request.get(path);
    expect(res.ok(), path).toBe(true);
    return ((await res.json()) as { items: { id: string }[] }).items;
  };
  const [connection] = await api(`/organizations/${state.org}/connections?limit=100`);
  const [project] = await api(`/organizations/${state.org}/projects?limit=100`);
  const made = await page.request.post(
    `/organizations/${state.org}/projects/${project?.id}/sync-targets`,
    {
      data: {
        name: "main",
        type: "gitlab-variables",
        connectionId: connection?.id,
        config: { project: state.gitlab.path },
        environmentMapping: { dev: "development" },
      },
    },
  );
  expect(made.ok(), await made.text()).toBe(true);
  await nav("Sync");
  await page.getByRole("button", { name: "Plan sync" }).click();
  const plan = page.getByRole("region", { name: "Plan for main" });
  await expect(plan).toBeVisible();
  // a plan changes nothing on the target
  expect((await gitlab("/variables")).body).toEqual([]);
  await plan.getByRole("button", { name: "Apply…" }).click();
  await page.getByRole("button", { name: "Apply plan" }).click();
  const card = page.getByRole("region", { name: "Sync target main" });
  await expect(
    card.locator("dt", { hasText: "Last sync" }).locator("xpath=following-sibling::dd[1]"),
  ).toHaveText(/^Applied \d{4}-/);

  // 5. GitLab holds the variables, and no screen showed the secret
  const held = Object.fromEntries(
    (
      (await gitlab("/variables")).body as {
        key: string;
        value: string;
        environment_scope: string;
      }[]
    ).map((v) => [`${v.key} ${v.environment_scope}`, v.value]),
  );
  expect(held).toEqual({ "API_KEY *": SECRET, "LOG_LEVEL development": "debug" });
  expect(await page.content()).not.toContain(SECRET);
  expect(await page.content()).not.toContain(state.gitlab.token);
});
